/** The current messages; a live binding, updated by setLang. */
export let L: Messages = zh;
export let lang: Lang = "zh";

export function setLang(l: Lang): void {
  lang = l === "en" ? "en" : "zh";
  L = lang === "en" ? en : zh;
  document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
}
